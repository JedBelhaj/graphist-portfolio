/* The site's one content source. Components call `await getContent()` and get
   a fully-populated object: Sanity's value where one is set, the original
   copy from content.ts where it isn't.

   The rules, so nothing on the page can come up empty:
   - Text: a blank field falls back to its default.
   - Lists (photos, FAQs, packages…): an empty list falls back to the default
     list. That keeps the mock gallery up until the first real photo lands;
     once one is published, Sanity's list replaces the mocks entirely.
   - No Sanity project configured, or the request fails: everything is the
     default, and the failure is logged rather than thrown. */

/* ---------- Output types ---------- */

/* A tile in the photo/video mosaics. `video` is a loop clip that replaces the
   still; `href` is the full film, played in the
   Lightbox when it is a YouTube/Vimeo link. */
export type MediaTile = { src: string; alt: string; video?: string; href?: string };
/* A video in a Videography section. `tall` is a 9:16 vertical, shown uncropped. */
export type VideoTile = MediaTile & { tall: boolean };
export type VideoSection = {
  key: string;
  client: string;
  photo: string;
  videos: VideoTile[];
  style: VideoStyle;
  side: VideoSide;
};
export type WebShot = { src: string; address: string; real: boolean };
export type Lane = { title: string; blurb: string; tags: string[] };
export type Country = { code: string; name: string; note: string | null };
export type ResultShot = { src: string; alt: string; label: string };
export type TeamMember = { name: string; role: string; focus: string; photo: string };
export type ServiceBubble = { label: string; bg: string; fg: string };
export type ServiceGroup = { title: string; icon: string; body: string; items: string[] };
export type Package = (typeof PACKAGES)[number];
export type Faq = { q: string; a: string };

/* ---------- Sanity shapes ----------
   Generated by TypeGen from the studio schema and CONTENT_QUERY below
   (`npm run typegen` in ../studio). Every field is optional: a half-filled
   document is normal, and the helpers below fill the gaps. */
type Raw = CONTENT_QUERY_RESULT;
type Doc<K extends keyof Raw> = Partial<NonNullable<Raw[K]>>;
type Img = SanityImageSource & { asset?: { _ref?: string } };
type MaybeHeading = { eyebrow?: string; title?: string; accent?: string; body?: string } | undefined;

/* Singletons by fixed ID (the _type filter is what lets TypeGen narrow each
   one to its own document type); collections in the order set in the studio.
   Items missing their required image are skipped rather than rendered broken,
   and so are items the editor switched to "Hide from website". */
const CONTENT_QUERY = defineQuery(`{
  "settings": *[_type == "siteSettings" && _id == "siteSettings"][0],
  "home": *[_type == "homePage" && _id == "homePage"][0],
  "about": *[_type == "aboutPage" && _id == "aboutPage"][0],
  "services": *[_type == "servicesPage" && _id == "servicesPage"][0],
  "work": *[_type == "workPage" && _id == "workPage"][0],
  "photography": *[_type == "photographyPage" && _id == "photographyPage"][0],
  "videography": *[_type == "videographyPage" && _id == "videographyPage"][0]{
    ...,
    "sections": sections[hidden != true]{
      _key, client, photo, style, side,
      "videos": videos[]->{ title, poster, "clip": clip.asset->url, link, format, hidden }
    }
  },
  "webDesign": *[_type == "webDesignPage" && _id == "webDesignPage"][0],
  "faq": *[_type == "faqPage" && _id == "faqPage"][0],
  "photos": *[_type == "photo" && defined(image.asset) && hidden != true] | order(orderRank)
    { image, alt, showInRecent, _createdAt },
  "videos": *[_type == "video" && defined(poster.asset) && hidden != true] | order(orderRank)
    { title, poster, "clip": clip.asset->url, link, showInRecent, _createdAt },
  "webProjects": *[_type == "webProject" && defined(screenshot.asset) && hidden != true] | order(orderRank)
    { title, screenshot, address },
  "testimonials": *[_type == "testimonial" && defined(quote) && hidden != true] | order(orderRank)
    { quote, name, tag, handle, avatar },
  "results": *[_type == "result" && defined(image.asset) && hidden != true] | order(orderRank)
    { image, label, alt },
  "team": *[_type == "teamMember" && defined(name) && hidden != true] | order(orderRank)
    { name, role, focus, photo },
  "logos": *[_type == "clientLogo" && defined(logo.asset) && hidden != true] | order(orderRank)
    { name, logo, size, tone }
}`);

/* ---------- Merge helpers ---------- */

const text = (value: string | undefined, fallback: string) => (value?.trim() ? value : fallback);

const list = <T>(value: T[] | null | undefined, fallback: T[]) =>
  Array.isArray(value) && value.length > 0 ? value : fallback;

const strings = (value: string[] | undefined, fallback: string[]) =>
  list(value?.filter((v) => v?.trim()), fallback);

const heading = (h: MaybeHeading = {}, fallback: Heading): Heading => {
  return {
    eyebrow: text(h.eyebrow, fallback.eyebrow),
    title: text(h.title, fallback.title),
    accent: text(h.accent, fallback.accent),
    body: text(h.body, fallback.body),
  };
};

const hasImage = (img: Img | null | undefined): img is Img => !!img?.asset?._ref;
const img = (value: Img | null | undefined, fallback: string, width?: number) =>
  hasImage(value) ? imageUrl(value, width) : fallback;

const blurbs = (value: Partial<Blurb>[] | undefined, fallback: Blurb[]) =>
  list(
    (value ?? []).flatMap((b) => (b.title ? [{ title: b.title, body: b.body ?? "" }] : [])),
    fallback,
  );

/* The mosaics tile in blocks of nine (see MediaMosaic). Past the first
   block, a partial one is held back so the bottom row stays flush. */
const fullBlocks = <T>(items: T[], size = 9) =>
  items.length <= size ? items : items.slice(0, items.length - (items.length % size));

const asTiles = (srcs: string[]): MediaTile[] => srcs.map((src) => ({ src, alt: "" }));

const lane = (l: Partial<Lane> = {}, fallback: Lane): Lane => {
  return { title: text(l.title, fallback.title), blurb: text(l.blurb, fallback.blurb), tags: strings(l.tags, fallback.tags) };
};

/* ---------- Build ---------- */

function build(raw: Raw | null) {
  const r: Raw = raw ?? {
    settings: null,
    home: null,
    about: null,
    services: null,
    work: null,
    photography: null,
    videography: null,
    webDesign: null,
    faq: null,
    photos: [],
    videos: [],
    webProjects: [],
    testimonials: [],
    results: [],
    team: [],
    logos: [],
  };
  const s: Doc<"settings"> = r.settings ?? {};
  const home: Doc<"home"> = r.home ?? {};
  const about: Doc<"about"> = r.about ?? {};
  const services: Doc<"services"> = r.services ?? {};
  const work: Doc<"work"> = r.work ?? {};
  const photography: Doc<"photography"> = r.photography ?? {};
  const videography: Doc<"videography"> = r.videography ?? {};
  const webDesign: Doc<"webDesign"> = r.webDesign ?? {};
  const faq: Doc<"faq"> = r.faq ?? {};

  const brand = {
    ...BRAND,
    name: text(s.name, BRAND.name),
    short: text(s.short, BRAND.short),
    founder: text(s.founder, BRAND.founder),
    email: text(s.email, BRAND.email),
    instagram: text(s.instagram, BRAND.instagram),
    facebook: text(s.facebook, BRAND.facebook),
    linkedin: text(s.linkedin, BRAND.linkedin),
  };

  const countries: Country[] = list(
    (s.countries ?? []).flatMap((c) =>
      c.code && c.name ? [{ code: c.code.toUpperCase(), name: c.name, note: c.note || null }] : [],
    ),
    COUNTRIES,
  );

  /* The non-null assertions on collection items are safe: CONTENT_QUERY only
     returns items whose required image or field is defined. */
  const photos = r.photos.map((p) => ({
    tile: { src: imageUrl(p.image!, 1800), alt: p.alt ?? "" } as MediaTile,
    recent: p.showInRecent,
    at: p._createdAt,
  }));
  const videos = r.videos.map((v) => ({
    tile: {
      src: imageUrl(v.poster!, 1800),
      alt: v.title ?? "",
      video: v.clip ?? undefined,
      href: v.link,
    } as MediaTile,
    recent: v.showInRecent,
    at: v._createdAt,
  }));

  const photoTiles = list(fullBlocks(photos.map((p) => p.tile)), asTiles(PHOTO_TILES));
  const videoTiles = list(videos.map((v) => v.tile), asTiles(VIDEO_TILES));

  /* Newest first across both lanes, so a fresh upload leads the grid. */
  const recent = list(
    [...photos, ...videos]
      .filter((m) => m.recent)
      .sort((a, b) => b.at.localeCompare(a.at))
      .slice(0, 7)
      .map((m) => m.tile),
    asTiles(WORK_IMAGES),
  );

  /* Real screenshots switch the wireframe overlay off (see BrowserFrame). */
  const webShots = list<WebShot>(
    r.webProjects.map((w) => ({
      src: imageUrl(w.screenshot!, 1600),
      address: w.address || w.title || "",
      real: true,
    })),
    WEB_SHOTS.map((src, i) => ({ src, address: ["yourbrand.com", "studio.example", "shop.example"][i], real: false })),
  );

  const logos: ClientLogo[] = list(
    r.logos.map((l) => ({
      name: l.name ?? "",
      src: imageUrl(l.logo!, 600),
      cap: LOGO_CAPS[l.size ?? "48"] ?? LOGO_CAPS["48"],
      tone: l.tone ?? undefined,
    })),
    CLIENT_LOGOS,
  );

  const testimonials: Testimonial[] = list(
    r.testimonials.map((t) => ({
      quote: t.quote!,
      name: t.name || null,
      tag: t.tag || null,
      handle: t.handle || null,
      /* No photo yet: keep the original placeholder for that person, if any. */
      avatar: hasImage(t.avatar)
        ? imageUrl(t.avatar, 160)
        : (TESTIMONIALS.find((d) => d.name && d.name === t.name)?.avatar ?? null),
    })),
    TESTIMONIALS,
  );

  const results: ResultShot[] = list(
    r.results.map((x) => ({ src: imageUrl(x.image!, 900), alt: x.alt || x.label || "", label: x.label ?? "" })),
    RESULTS,
  );

  /* A member without a photo keeps their original placeholder, or gets a
     stand-in seeded from their name, so a new hire can go live before their
     portrait is shot. */
  const team: TeamMember[] = list(
    r.team.map((m) => ({
      name: m.name!,
      role: m.role ?? "",
      focus: m.focus ?? "",
      photo: img(
        m.photo,
        TEAM.find((d) => d.name === m.name)?.photo ??
          `https://picsum.photos/seed/soltani-team-${encodeURIComponent(m.name!)}/640/800`,
        800,
      ),
    })),
    TEAM,
  );

  const bubbles: ServiceBubble[] = list<{ label: string; color: ServiceColor }>(
    (services.bubbles ?? []).flatMap((b) => (b.label ? [{ label: b.label, color: b.color ?? "accent" }] : [])),
    SERVICES,
  ).map((b) => ({ label: b.label, ...SERVICE_COLORS[b.color] }));

  const groups: ServiceGroup[] = list(
    (services.groups ?? []).flatMap((g) =>
      g.title ? [{ title: g.title, icon: g.icon ?? "camera", body: g.body ?? "", items: strings(g.items, []) }] : [],
    ),
    SERVICE_GROUPS,
  );

  const packages: Package[] = list(
    (services.packages ?? []).flatMap((p) =>
      p.name
        ? [
            {
              name: p.name,
              price: p.price ?? "",
              cadence: p.cadence ?? "",
              pitch: p.pitch ?? "",
              features: strings(p.features, []),
              featured: !!p.featured,
            },
          ]
        : [],
    ),
    PACKAGES,
  );

  const toolbox = list(
    (services.toolbox ?? []).filter(hasImage).map((t) => imageUrl(t, 300)),
    TOOLBOX,
  );

  const faqs: Faq[] = list(
    (faq.faqs ?? []).flatMap((f) => (f.q && f.a ? [{ q: f.q, a: f.a }] : [])),
    FAQS,
  );

  /* A section needs a client name and at least one visible video; a missing
     photo falls back to the first poster. "auto" takes the style and side from
     the section's position: the side alternates, the style rotates. */
  const videoSections: VideoSection[] = list<
    Omit<VideoSection, "style" | "side"> & { style?: string | null; side?: string | null }
  >(
    (videography.sections ?? []).flatMap((s) => {
      const clips: VideoTile[] = (s.videos ?? []).flatMap((v) =>
        v && hasImage(v.poster) && !v.hidden
          ? [
              {
                src: imageUrl(v.poster, 1600),
                alt: v.title ?? "",
                video: v.clip ?? undefined,
                href: v.link ?? undefined,
                tall: v.format === "vertical",
              },
            ]
          : [],
      );
      if (!s.client || clips.length === 0) return [];
      return [
        {
          key: s._key,
          client: s.client,
          photo: img(s.photo, clips[0].src, 1600),
          videos: clips,
          style: s.style,
          side: s.side,
        },
      ];
    }),
    VIDEO_SECTIONS.map((s) => ({ ...s, key: s.client, videos: s.videos.map((v) => ({ ...v, alt: "" })) })),
  ).map((s, i) => ({
    ...s,
    style: VIDEO_STYLES.find((x) => x === s.style) ?? VIDEO_STYLES[i % VIDEO_STYLES.length],
    side: s.side === "left" || s.side === "right" ? s.side : i % 2 ? "right" : "left",
  }));

  const stats = list(
    (videography.stats ?? []).flatMap((x) => (x.figure && x.label ? [{ figure: x.figure, label: x.label }] : [])),
    VIDEO_STATS,
  );

  return {
    brand,
    seo: {
      title: text(s.seoTitle, COPY.site.seoTitle),
      description: text(s.seoDescription, COPY.site.seoDescription),
    },
    images: {
      hero: img(s.heroPhoto, HERO_PHOTO, 1400),
      studio: img(s.studioPhoto, STUDIO_PHOTO, 1200),
      founder: img(s.founderPortrait, FOUNDER_PORTRAIT, 700),
    },
    footer: {
      cta: text(s.footerCta, COPY.site.footerCta),
      button: text(s.footerButton, COPY.site.footerButton),
      founderCaption: text(s.founderCaption, COPY.site.founderCaption),
    },
    countries,
    logos,
    testimonials,
    results,
    team,

    home: {
      heroLine1: text(home.heroLine1, COPY.home.heroLine1),
      heroLine2: text(home.heroLine2, COPY.home.heroLine2),
      heroLine3: text(home.heroLine3, COPY.home.heroLine3),
      heroTagline: text(home.heroTagline, COPY.home.heroTagline),
      heroIntro: text(home.heroIntro, COPY.home.heroIntro),
      heroButton: text(home.heroButton, COPY.home.heroButton),
      heroStickers: list(
        (home.heroStickers ?? []).filter(hasImage).map((t) => imageUrl(t, 300)),
        HERO_STICKERS,
      ),
      results: heading(home.results, COPY.home.results),
      projectsDelivered: text(home.projectsDelivered, COPY.home.projectsDelivered),
      testimonials: heading(home.testimonials, COPY.home.testimonials),
      work: heading(home.work, COPY.home.work),
      marqueeOne: text(home.marqueeOne, COPY.home.marqueeOne),
      services: heading(home.services, COPY.home.services),
      marqueeTwo: text(home.marqueeTwo, COPY.home.marqueeTwo),
    },

    about: {
      intro: heading(about.intro, COPY.about.intro),
      aboutTitle: text(about.aboutTitle, COPY.about.aboutTitle),
      /* The layout has exactly three slots; anything else keeps the default. */
      principles: (() => {
        const p = blurbs(about.principles, COPY.about.principles);
        return p.length === 3 ? p : COPY.about.principles;
      })(),
      photoCaption: text(about.photoCaption, COPY.about.photoCaption),
      team: heading(about.team, COPY.about.team),
      countries: heading(about.countries, COPY.about.countries),
    },

    services: {
      hero: heading(services.hero, COPY.services.hero),
      bubbles,
      groups,
      toolboxTitle: text(services.toolboxTitle, COPY.services.toolboxTitle),
      toolbox,
      packagesHeading: heading(services.packagesHeading, COPY.services.packagesHeading),
      packages,
      packagesFootnote: text(services.packagesFootnote, COPY.services.packagesFootnote),
    },

    work: {
      hero: heading(work.hero, COPY.work.hero),
      lanes: {
        photo: { ...lane(work.photoLane, COPY.work.photoLane), img: photoTiles[0].src },
        video: { ...lane(work.videoLane, COPY.work.videoLane), img: videoTiles[0].src },
        web: { ...lane(work.webLane, COPY.work.webLane), img: webShots[0].src, real: webShots[0].real },
      },
      recentTitle: text(work.recentTitle, COPY.work.recentTitle),
      tabs: strings(work.tabs, WORK_TABS),
      recent,
    },

    photography: {
      hero: heading(photography.hero, COPY.photography.hero),
      heading: heading(photography.heading, COPY.photography.heading),
      disciplines: strings(photography.disciplines, PHOTO_DISCIPLINES),
      tiles: photoTiles,
    },

    videography: {
      hero: heading(videography.hero, COPY.videography.hero),
      heading: heading(videography.heading, COPY.videography.heading),
      capabilities: blurbs(videography.capabilities, VIDEO_CAPABILITIES),
      stats,
      sections: videoSections,
    },

    webDesign: {
      hero: heading(webDesign.hero, COPY.webDesign.hero),
      heading: heading(webDesign.heading, COPY.webDesign.heading),
      capabilitiesTitle: text(webDesign.capabilitiesTitle, COPY.webDesign.capabilitiesTitle),
      capabilities: blurbs(webDesign.capabilities, WEB_CAPABILITIES),
      processHeading: heading(webDesign.processHeading, COPY.webDesign.processHeading),
      process: blurbs(webDesign.process, WEB_PROCESS.map((p) => ({ title: p.step, body: p.body }))),
      shots: webShots,
    },

    faq: {
      hero: heading(faq.hero, COPY.faq.hero),
      faqs,
      ctaTitle: text(faq.ctaTitle, COPY.faq.ctaTitle),
      ctaButton: text(faq.ctaButton, COPY.faq.ctaButton),
    },
  };
}

export type SiteContent = ReturnType<typeof build>;

/* cache() so the dozen components on a page share one request. */
export const getContent = cache(async (): Promise<SiteContent> => {
  try {
    return build(await sanityFetch<Raw>(CONTENT_QUERY));
  } catch (err) {
    console.error("[cms] Sanity fetch failed, rendering defaults:", err);
    return build(null);
  }
});
